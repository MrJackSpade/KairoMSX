#!/usr/bin/env python3
"""Writes the headers openMSX's build generates into core/generated/, for KairoMSX's build.

Usage: generate_openmsx.py

They hold what openMSX's build scripts (third_party/openmsx/build/*2code.py) write for this
build: components.hh (only the emulation core; no GL renderer, laserdisc or ALSA MIDI),
systemfuncs.hh, Version.ii (the release in build/version.py) and build-info.hh. KairoMSX builds
openMSX as a generic platform on every target: the app sets OPENMSX_HOME and OPENMSX_SYSTEM_DATA,
so openMSX needs no Android-specific paths, which would call into SDL's Android activity.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OPENMSX = ROOT / 'third_party/openmsx'
OUT = ROOT / 'core/generated'


def version():
    text = (OPENMSX / 'build/version.py').read_text(encoding='utf-8')
    number = re.search(r"^packageVersionNumber = '([^']+)'", text, re.M)[1]
    suffix = re.search(r"^packageVersionSuffix = '([^']*)'", text, re.M)[1]
    release = re.search(r'^releaseFlag = (True|False)', text, re.M)[1] == 'True'
    year = re.search(r"^releaseYear = '([^']+)'", text, re.M)[1]
    if not release:
        raise SystemExit('openMSX snapshot is not a release: Version::REVISION needs its Git revision')
    return number + suffix, year


FILES = {
    'components.hh': '''// Generated by tools/generate_openmsx.py; do not edit.

#ifndef COMPONENTS_HH
#define COMPONENTS_HH

#define COMPONENT_CORE 1
#define COMPONENT_GL 0
#define COMPONENT_LASERDISC 0
#define COMPONENT_ALSAMIDI 0

namespace openmsx {

static const char* const BUILD_COMPONENTS = "CORE";

} // namespace openmsx

#endif // COMPONENTS_HH
''',
    'systemfuncs.hh': '''// Generated by tools/generate_openmsx.py; do not edit.

#ifndef SYSTEMFUNCS_HH
#define SYSTEMFUNCS_HH

#ifdef _WIN32
#define HAVE_FTRUNCATE 0
#define HAVE_MMAP 0
#else
#define HAVE_FTRUNCATE 1
#define HAVE_MMAP 1
#endif

#endif // SYSTEMFUNCS_HH
''',
    'build-info.hh': '''// Generated by tools/generate_openmsx.py; do not edit.

#ifndef BUILD_INFO_HH
#define BUILD_INFO_HH

#define PLATFORM_ANDROID 0
#define MIN_SCALE_FACTOR 2
#define MAX_SCALE_FACTOR 4

namespace openmsx {

static const bool OPENMSX_SET_WINDOW_ICON = false;
// KairoMSX sets OPENMSX_SYSTEM_DATA, which openMSX reads before these.
static const char* const DATADIR = "";
static const char* const DOCDIR = "";
static const char* const BUILD_FLAVOUR = "kairomsx";
static const char* const TARGET_PLATFORM = "kairomsx";
static const char* const TARGET_CPU = "kairomsx";

} // namespace openmsx

#endif // BUILD_INFO_HH
''',
}


def main():
    number, year = version()
    OUT.mkdir(parents=True, exist_ok=True)
    files = dict(FILES)
    files['Version.ii'] = (
        '// Generated by tools/generate_openmsx.py; do not edit.\n'
        'const bool Version::RELEASE = true;\n'
        f'const char* const Version::VERSION = "{number}";\n'
        'const char* const Version::REVISION = "";\n'
        f'const char* const Version::COPYRIGHT = "Copyright 2001-{year}";\n')
    for name, text in files.items():
        (OUT / name).write_text(text, encoding='utf-8', newline='\n')
    print(f'openMSX {number}: wrote {", ".join(files)} to {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
